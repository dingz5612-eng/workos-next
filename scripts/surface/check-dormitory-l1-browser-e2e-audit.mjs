import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const latestPath = path.join(root, "artifacts", "oam", "evidence", "dormitory-l1-browser-e2e", "latest-report.json");
const graphPath = path.join(root, "artifacts", "oam", "evidence", "evidence-graph.json");
const requiredScenarios = new Set([
  "dormitory_l1_positive_normal",
  "dormitory_l1_negative_illegal_access",
  "dormitory_l1_negative_unauthorized",
  "dormitory_l1_negative_wrong_status"
]);

const reportRef = process.argv[2] || readLatestReportRef();
const reportPath = path.join(root, reportRef);
const report = readJson(reportPath);
const graph = readJson(graphPath);
const violations = [];

if (report.browserMode !== "playwright-real-browser") {
  violations.push("Report must be generated by a real Playwright browser.");
}
if (!/no route mocks/i.test(report.mockPolicy || "")) {
  violations.push("Report must declare no route mocks / no backend simulation.");
}
if (!/no localStorage injection/i.test(report.mockPolicy || "")) {
  violations.push("Report must declare no localStorage injection.");
}
if (report.status !== "passed") {
  violations.push(`Report status must be passed, got ${report.status}.`);
}

const scenarioIds = new Set((report.scenarios || []).map((scenario) => scenario.scenarioId));
for (const scenarioId of requiredScenarios) {
  if (!scenarioIds.has(scenarioId)) violations.push(`Missing scenario: ${scenarioId}`);
}

for (const scenario of report.scenarios || []) {
  if (scenario.status !== "passed") violations.push(`Scenario ${scenario.scenarioId} is not passed.`);
  if (!scenario.steps?.length) violations.push(`Scenario ${scenario.scenarioId} has no steps.`);
  for (const step of scenario.steps || []) {
    if (!step.url) violations.push(`${scenario.scenarioId}/${step.stepId} missing URL.`);
    if (!step.domState) violations.push(`${scenario.scenarioId}/${step.stepId} missing DOM state.`);
    if (!Object.hasOwn(step, "admissionDecision")) violations.push(`${scenario.scenarioId}/${step.stepId} missing admission decision.`);
    if (!Object.hasOwn(step, "runtimeDecision")) violations.push(`${scenario.scenarioId}/${step.stepId} missing runtime decision.`);
    if (!Array.isArray(step.clickSequence)) violations.push(`${scenario.scenarioId}/${step.stepId} missing click sequence.`);
    validateScreenshot(step.screenshot?.fullPage, `${scenario.scenarioId}/${step.stepId}/fullPage`);
    if (!step.screenshot?.segments?.length) violations.push(`${scenario.scenarioId}/${step.stepId} missing scroll segment screenshots.`);
    for (const segment of step.screenshot?.segments || []) {
      validateScreenshot(segment, `${scenario.scenarioId}/${step.stepId}/segment`);
    }
  }
}

const steps = (report.scenarios || []).flatMap((scenario) => scenario.steps || []);
if (!steps.some((step) => step.runtimeDecision === "blocked:required_field_missing")) {
  violations.push("Missing blocked required-field runtime decision.");
}
if (!steps.some((step) => step.admissionDecision === "visible_readonly_completed")) {
  violations.push("Missing completed read-only admission decision.");
}
if (!steps.some((step) => step.domState?.surface === "permission-diagnostic")) {
  violations.push("Missing unauthorized permission diagnostic page.");
}
if (!steps.filter((step) => step.admissionDecision === "visible_readonly_completed")
  .every((step) => step.domState?.submitCount === 0)) {
  violations.push("Completed read-only steps must not expose submit CTA.");
}

if (report.networkPolicy?.noRetiredWorkspaceCardWrites !== true) {
  violations.push("Network policy detected retired workspace/card write path.");
}
if (!report.networkPolicy?.operationsRuntimeWrites?.length) {
  violations.push("Network policy did not observe Operations Runtime prepare/confirm writes.");
}
if (report.networkPolicy?.noDirectBusinessFactWrites !== true) {
  violations.push("Network policy detected direct business fact writes.");
}

if (!report.git?.headSha) violations.push("Report missing commit SHA.");
if (!report.ciRun?.id) violations.push("Report missing CI run ID binding.");

const node = (graph.nodes || []).find((candidate) =>
  candidate.type === "browser_e2e_evidence" &&
  candidate.refs?.includes(normalizeRef(reportRef)));
if (!node) {
  violations.push("Evidence Graph missing browser_e2e_evidence node for this report.");
} else {
  if (node.headSha !== report.git.headSha) violations.push("Evidence Graph node headSha does not match report.");
  if (node.ciRunId !== report.ciRun.id) violations.push("Evidence Graph node ciRunId does not match report.");
  if (!node.screenshotHashes?.length) violations.push("Evidence Graph node missing screenshot hashes.");
  const edge = (graph.edges || []).find((candidate) =>
    candidate.from === node.id &&
    candidate.to === "L1_INTERNAL_PILOT_OBSERVATION" &&
    candidate.relation === "binds_browser_evidence");
  if (!edge) violations.push("Evidence Graph missing L1 observation binding edge.");
}

if (violations.length) {
  console.error("check-dormitory-l1-browser-e2e-audit: FAIL");
  for (const violation of violations) console.error(`- ${violation}`);
  process.exit(1);
}

console.log(`check-dormitory-l1-browser-e2e-audit: PASS (${report.runId}, screenshots=${report.screenshots.length})`);

function validateScreenshot(entry, label) {
  if (!entry?.path) {
    violations.push(`${label} missing path.`);
    return;
  }
  if (!entry.sha256) violations.push(`${label} missing sha256.`);
  for (const field of ["scenarioId", "stepId", "role", "language", "url", "admissionState", "runtimeDecision", "commitSha", "ciRun"]) {
    if (!entry[field]) violations.push(`${label} missing ${field}.`);
  }
  const filePath = path.join(root, entry.path);
  if (!fs.existsSync(filePath)) violations.push(`${label} file does not exist: ${entry.path}`);
  if (entry.bytes <= 0) violations.push(`${label} has no bytes.`);
}

function readLatestReportRef() {
  if (!fs.existsSync(latestPath)) {
    throw new Error("Missing latest Dormitory L1 browser E2E report. Run scripts/surface/run-dormitory-l1-browser-e2e-audit.mjs first.");
  }
  return readJson(latestPath).report;
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function normalizeRef(value) {
  return String(value || "").replace(/\\/g, "/");
}
