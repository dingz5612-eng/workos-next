import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const compilerPath = "scripts/oam/compile-current-capability.mjs";
const resultPath = "artifacts/oam/checks/capability-compiler-consumes-business-authority-result.json";
const compilerSource = readText(compilerPath);
const failures = [];
const requiredInputPaths = [
  "docs/oam/capabilities/dormitory-first-golden-chain.authority-ledger.json",
  "docs/oam/capabilities/dormitory-first-golden-chain.current.json",
  "docs/oam/generated-candidate-acceptance.current.json",
  "docs/business/domains/dormitory/dormitory-first-golden-chain.capability-decision.authority.json",
  "docs/business/domains/dormitory/dormitory-object-graph.authority.json",
  "docs/business/domains/dormitory/dormitory-bed-cardinality.authority.json",
  "docs/business/domains/dormitory/dormitory-invariants.authority.json",
  "docs/business/domains/dormitory/dormitory-command-contracts.authority.json",
  "docs/business/domains/dormitory/dormitory-failure-semantics.authority.json",
  "docs/oam/dormitory-runtime-admission.current.json",
  "docs/oam/dormitory-first-golden-chain-landing.current.json",
  "docs/oam/environment-profiles/current-runtime-evidence.environment-profile.json"
];
const requiredGeneratedOutputs = [
  "docs/contracts/generated/dormitory/object-identity.generated.json",
  "docs/contracts/generated/dormitory/bed-cardinality.generated.json",
  "docs/contracts/generated/dormitory/business-invariants.generated.json",
  "docs/contracts/generated/dormitory/command-contracts.generated.json",
  "docs/contracts/generated/dormitory/failure-semantics.generated.json",
  "docs/contracts/generated/dormitory/rule-source-map.generated.json",
  "apps/mobile/src/generated/oam/dormitory-surface-input-model.generated.json",
  "apps/mobile/src/generated/oam/capability-projection.generated.json",
  "services/core-api/WorkOS.Api/Runtime/GeneratedCapabilityRuntimeProjection.generated.json",
  "docs/contracts/generated/dormitory/db-projection-policy.generated.json",
  "docs/contracts/generated/dormitory/test-plan.generated.json",
  "artifacts/oam/evidence/capability-evidence-subject-chain.json"
];
const sourceMarkers = new Map([
  ["docs/oam/capabilities/dormitory-first-golden-chain.authority-ledger.json", "CAPABILITY_LEDGER_PATH"],
  ["docs/oam/capabilities/dormitory-first-golden-chain.current.json", "CAPABILITY_PROJECTION_PATH"],
  ["docs/oam/generated-candidate-acceptance.current.json", "GENERATED_CANDIDATE_ACCEPTANCE_PATH"]
]);
const generatedDocuments = requiredGeneratedOutputs.map((file) => [file, readJson(file)]).filter(([, document]) => document);

for (const file of [...requiredInputPaths, ...requiredGeneratedOutputs]) {
  if (!exists(file)) fail(`${file} is missing.`);
}
for (const file of requiredInputPaths) {
  const marker = sourceMarkers.get(file) ?? file;
  if (!compilerSource.includes(marker)) fail(`${compilerPath} must name input ${file}.`);
}
for (const file of requiredGeneratedOutputs) {
  if (!compilerSource.includes(file)) fail(`${compilerPath} must name output ${file}.`);
}
for (const [file, document] of generatedDocuments) {
  if (document.generated !== true) fail(`${file} must be generated.`);
  if (document.doNotEdit !== true) fail(`${file} must be doNotEdit.`);
  if (document.generatedBy !== compilerPath) fail(`${file} must be generated by ${compilerPath}.`);
  for (const inputPath of requiredInputPaths) {
    if (!(document.generatedFrom ?? []).includes(inputPath)) {
      fail(`${file} generatedFrom must include ${inputPath}.`);
    }
  }
  if (document.capabilityLedgerReplay?.status !== "PASS") fail(`${file} must include capability ledger replay PASS.`);
  if (!isDigest(document.acceptedGeneratedBundleDigest)) fail(`${file} must bind acceptedGeneratedBundleDigest.`);
  if (!isDigest(document.outputContentDigest)) fail(`${file} must carry outputContentDigest.`);
  const expectedDigest = stableDigest({ ...document, outputContentDigest: "sha256:pending" });
  if (document.outputContentDigest !== expectedDigest) fail(`${file} outputContentDigest mismatch.`);
}

const subjectChain = readJson("artifacts/oam/evidence/capability-evidence-subject-chain.json");
if (subjectChain) {
  const authorityDigestPaths = new Set((subjectChain.businessAuthorityDigests ?? []).map((item) => item.path));
  for (const file of requiredInputPaths.filter((item) => item.startsWith("docs/business/domains/dormitory/"))) {
    if (!authorityDigestPaths.has(file)) fail(`subject chain must bind authority digest for ${file}.`);
  }
}

writeResult({
  version: "oam.capability-compiler-consumes-business-authority-check.v1",
  status: failures.length === 0 ? "PASS" : "NO_GO",
  compilerPath,
  requiredInputPaths,
  requiredGeneratedOutputs,
  failures
});

if (failures.length) {
  console.error("Capability compiler consumes business authority check: FAIL");
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log("Capability compiler consumes business authority check: PASS");

function readText(file) {
  const full = path.join(root, file);
  if (!fs.existsSync(full)) return "";
  return fs.readFileSync(full, "utf8");
}

function readJson(file) {
  const full = path.join(root, file);
  if (!fs.existsSync(full)) {
    fail(`${file} is missing.`);
    return null;
  }
  try {
    return JSON.parse(fs.readFileSync(full, "utf8"));
  } catch (error) {
    fail(`${file} is not valid JSON: ${error.message}`);
    return null;
  }
}

function exists(file) {
  return fs.existsSync(path.join(root, file));
}

function writeResult(result) {
  const full = path.join(root, resultPath);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, `${JSON.stringify({ ...result, checkedAtUtc: new Date().toISOString() }, null, 2)}\n`, "utf8");
}

function stableDigest(value) {
  return `sha256:${crypto.createHash("sha256").update(stableStringify(value)).digest("hex")}`;
}

function stableStringify(value) {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

function isDigest(value) {
  return /^sha256:[a-f0-9]{64}$/.test(String(value ?? ""));
}

function fail(message) {
  failures.push(message);
}
